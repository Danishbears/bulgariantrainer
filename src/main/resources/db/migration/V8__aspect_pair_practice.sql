CREATE TABLE aspect_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL UNIQUE,
    settings_json CLOB NOT NULL,
    total_questions INTEGER NOT NULL CHECK (total_questions BETWEEN 1 AND 100),
    current_position INTEGER DEFAULT 1 NOT NULL,
    correct_answers INTEGER DEFAULT 0 NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('IN_PROGRESS','COMPLETED','ABANDONED')),
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    CHECK (current_position BETWEEN 1 AND total_questions + 1),
    CHECK (correct_answers BETWEEN 0 AND total_questions),
    CHECK ((status = 'IN_PROGRESS' AND completed_at IS NULL) OR (status <> 'IN_PROGRESS' AND completed_at IS NOT NULL)),
    CHECK (completed_at IS NULL OR completed_at >= started_at)
);
CREATE TABLE aspect_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES aspect_sessions(id),
    pair_id BIGINT NOT NULL REFERENCES aspect_pairs(id),
    position INTEGER NOT NULL CHECK (position > 0),
    direction VARCHAR(40) NOT NULL CHECK (direction IN ('IMPERFECTIVE_TO_PERFECTIVE','PERFECTIVE_TO_IMPERFECTIVE')),
    snapshot_json CLOB NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    acknowledged BOOLEAN DEFAULT FALSE NOT NULL,
    revealed_at TIMESTAMP(6) WITH TIME ZONE,
    UNIQUE(session_id, position), UNIQUE(session_id, pair_id)
);
CREATE INDEX idx_aspect_questions_pair ON aspect_questions(pair_id);
CREATE TABLE aspect_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL UNIQUE REFERENCES aspect_questions(id),
    user_answer VARCHAR(4000),
    outcome VARCHAR(30) NOT NULL CHECK (outcome IN ('CORRECT','INCORRECT','REVEALED')),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CHECK ((outcome = 'REVEALED' AND user_answer IS NULL) OR
           (outcome <> 'REVEALED' AND user_answer IS NOT NULL AND CHAR_LENGTH(TRIM(user_answer)) > 0))
);
