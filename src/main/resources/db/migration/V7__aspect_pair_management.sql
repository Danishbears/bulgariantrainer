CREATE TABLE aspect_datasets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace VARCHAR(100) NOT NULL UNIQUE,
    metadata_json CLOB NOT NULL,
    content_revision VARCHAR(64),
    version BIGINT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE aspect_pairs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL REFERENCES aspect_datasets(id),
    external_id VARCHAR(100) NOT NULL,
    imperfective VARCHAR(255) NOT NULL,
    perfective VARCHAR(255) NOT NULL,
    russian_imperfective VARCHAR(1000) NOT NULL,
    russian_perfective VARCHAR(1000) NOT NULL,
    topic VARCHAR(255) NOT NULL,
    study_stage INTEGER NOT NULL CHECK (study_stage BETWEEN 1 AND 3),
    relation_type VARCHAR(30) NOT NULL CHECK (relation_type IN ('core','resultative','bounded')),
    note VARCHAR(4000) NOT NULL,
    provenance_json CLOB NOT NULL,
    examples_json CLOB,
    search_text VARCHAR(64000) NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    archived BOOLEAN DEFAULT FALSE NOT NULL,
    version BIGINT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UNIQUE(dataset_id, external_id),
    CHECK (CHAR_LENGTH(TRIM(external_id)) > 0 AND CHAR_LENGTH(TRIM(imperfective)) > 0
        AND CHAR_LENGTH(TRIM(perfective)) > 0 AND CHAR_LENGTH(TRIM(russian_imperfective)) > 0
        AND CHAR_LENGTH(TRIM(russian_perfective)) > 0 AND CHAR_LENGTH(TRIM(topic)) > 0)
);
CREATE INDEX idx_aspect_pairs_filters ON aspect_pairs(dataset_id, archived, study_stage, topic, id);
CREATE TABLE aspect_pair_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pair_id BIGINT NOT NULL REFERENCES aspect_pairs(id),
    side VARCHAR(20) NOT NULL CHECK (side IN ('IMPERFECTIVE','PERFECTIVE')),
    position INTEGER NOT NULL CHECK (position > 0),
    answer_text VARCHAR(255) NOT NULL CHECK (CHAR_LENGTH(TRIM(answer_text)) > 0),
    normalized_key VARCHAR(255) NOT NULL,
    UNIQUE(pair_id, side, position), UNIQUE(pair_id, side, normalized_key)
);
CREATE TABLE aspect_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pair_id BIGINT NOT NULL REFERENCES aspect_pairs(id),
    direction VARCHAR(40) NOT NULL CHECK (direction IN ('IMPERFECTIVE_TO_PERFECTIVE','PERFECTIVE_TO_IMPERFECTIVE')),
    total_attempts INTEGER DEFAULT 0 NOT NULL,
    correct_attempts INTEGER DEFAULT 0 NOT NULL,
    successful_review_count INTEGER DEFAULT 0 NOT NULL,
    consecutive_correct INTEGER DEFAULT 0 NOT NULL,
    last_reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    next_review_at TIMESTAMP(6) WITH TIME ZONE,
    repetition_interval INTEGER DEFAULT 0 NOT NULL,
    UNIQUE(pair_id, direction),
    CHECK (total_attempts >= 0 AND correct_attempts BETWEEN 0 AND total_attempts
        AND successful_review_count BETWEEN 0 AND correct_attempts
        AND consecutive_correct BETWEEN 0 AND correct_attempts AND repetition_interval >= 0)
);
CREATE INDEX idx_aspect_progress_due ON aspect_progress(direction, next_review_at);
CREATE TABLE aspect_import_receipts (
    request_id UUID PRIMARY KEY,
    import_id UUID NOT NULL UNIQUE,
    dataset_id BIGINT NOT NULL REFERENCES aspect_datasets(id),
    request_hash VARCHAR(64) NOT NULL,
    file_hash VARCHAR(64) NOT NULL,
    metadata_json CLOB NOT NULL,
    summary_json CLOB NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
