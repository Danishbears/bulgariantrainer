CREATE TABLE flashcard_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    word_id BIGINT NOT NULL,
    position INTEGER NOT NULL,
    direction VARCHAR(30) NOT NULL,
    bulgarian_text VARCHAR(255) NOT NULL,
    russian_texts VARCHAR(14000) NOT NULL,
    revealed_at TIMESTAMP(6) WITH TIME ZONE,
    attempt_id BIGINT,
    CONSTRAINT fk_flashcards_session FOREIGN KEY (session_id) REFERENCES study_sessions(id),
    CONSTRAINT fk_flashcards_word FOREIGN KEY (word_id) REFERENCES words(id),
    CONSTRAINT fk_flashcards_attempt FOREIGN KEY (attempt_id) REFERENCES study_attempts(id),
    CONSTRAINT uk_flashcards_position UNIQUE (session_id, position),
    CONSTRAINT uk_flashcards_word UNIQUE (session_id, word_id),
    CONSTRAINT uk_flashcards_attempt UNIQUE (attempt_id),
    CONSTRAINT ck_flashcards_position CHECK (position >= 1),
    CONSTRAINT ck_flashcards_direction CHECK (direction IN ('BG_TO_RU', 'RU_TO_BG')),
    CONSTRAINT ck_flashcards_revealed CHECK (attempt_id IS NULL OR revealed_at IS NOT NULL)
);
CREATE INDEX idx_flashcards_word ON flashcard_questions(word_id);
