ALTER TABLE study_sessions ADD COLUMN typing_request_id UUID UNIQUE;
ALTER TABLE study_sessions ADD COLUMN shorter_accepted BOOLEAN;
CREATE TABLE typing_questions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id BIGINT NOT NULL REFERENCES study_sessions(id),
 word_id BIGINT NOT NULL REFERENCES words(id),
 position INTEGER NOT NULL CHECK (position > 0),
 direction VARCHAR(30) NOT NULL CHECK (direction IN ('BG_TO_RU','RU_TO_BG')),
 bulgarian_text VARCHAR(255) NOT NULL,
 russian_texts VARCHAR(14000) NOT NULL,
 acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
 attempt_id BIGINT UNIQUE REFERENCES study_attempts(id),
 UNIQUE(session_id, position), UNIQUE(session_id, word_id),
 CHECK (NOT acknowledged OR attempt_id IS NOT NULL)
);
CREATE INDEX idx_typing_word ON typing_questions(word_id);
