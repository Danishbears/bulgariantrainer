CREATE TABLE words (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bulgarian_text VARCHAR(255) NOT NULL,
    normalized_text VARCHAR(255) NOT NULL,
    part_of_speech VARCHAR(100),
    grammatical_gender VARCHAR(100),
    notes VARCHAR(4000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_words_normalized_text UNIQUE (normalized_text),
    CONSTRAINT ck_words_text CHECK (CHAR_LENGTH(TRIM(bulgarian_text)) > 0)
);

CREATE TABLE translations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_id BIGINT NOT NULL,
    russian_text VARCHAR(255) NOT NULL,
    normalized_text VARCHAR(255) NOT NULL,
    is_primary BOOLEAN NOT NULL,
    CONSTRAINT fk_translations_word FOREIGN KEY (word_id) REFERENCES words(id),
    CONSTRAINT uk_translations_word_text UNIQUE (word_id, normalized_text),
    CONSTRAINT ck_translations_text CHECK (CHAR_LENGTH(TRIM(russian_text)) > 0)
);
CREATE INDEX idx_translations_normalized_text ON translations(normalized_text);

CREATE TABLE sentences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bulgarian_text VARCHAR(4000) NOT NULL,
    russian_text VARCHAR(4000) NOT NULL,
    explanation VARCHAR(4000),
    difficulty INTEGER,
    CONSTRAINT ck_sentences_difficulty CHECK (difficulty BETWEEN 1 AND 5),
    CONSTRAINT ck_sentences_text CHECK (CHAR_LENGTH(TRIM(bulgarian_text)) > 0 AND CHAR_LENGTH(TRIM(russian_text)) > 0)
);

CREATE TABLE sentence_words (
    sentence_id BIGINT NOT NULL,
    word_id BIGINT NOT NULL,
    PRIMARY KEY (sentence_id, word_id),
    CONSTRAINT fk_sentence_words_sentence FOREIGN KEY (sentence_id) REFERENCES sentences(id),
    CONSTRAINT fk_sentence_words_word FOREIGN KEY (word_id) REFERENCES words(id)
);
CREATE INDEX idx_sentence_words_word ON sentence_words(word_id);

CREATE TABLE study_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_id BIGINT NOT NULL,
    training_mode VARCHAR(30) NOT NULL,
    total_attempts INTEGER DEFAULT 0 NOT NULL,
    correct_attempts INTEGER DEFAULT 0 NOT NULL,
    consecutive_correct INTEGER DEFAULT 0 NOT NULL,
    last_reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    next_review_at TIMESTAMP(6) WITH TIME ZONE,
    repetition_interval INTEGER DEFAULT 0 NOT NULL,
    ease_factor DOUBLE PRECISION DEFAULT 2.5 NOT NULL,
    CONSTRAINT fk_study_progress_word FOREIGN KEY (word_id) REFERENCES words(id),
    CONSTRAINT uk_study_progress_word_mode UNIQUE (word_id, training_mode),
    CONSTRAINT ck_progress_mode CHECK (training_mode IN ('FLASHCARD', 'TYPING', 'SENTENCE')),
    CONSTRAINT ck_progress_counts CHECK (total_attempts >= 0 AND correct_attempts BETWEEN 0 AND total_attempts AND consecutive_correct BETWEEN 0 AND correct_attempts),
    CONSTRAINT ck_progress_schedule CHECK (repetition_interval >= 0 AND ease_factor >= 1.3)
);
CREATE INDEX idx_study_progress_due ON study_progress(training_mode, next_review_at);

CREATE TABLE study_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    training_mode VARCHAR(30) NOT NULL,
    started_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP(6) WITH TIME ZONE,
    total_questions INTEGER DEFAULT 0 NOT NULL,
    correct_answers INTEGER DEFAULT 0 NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT ck_session_mode CHECK (training_mode IN ('FLASHCARD', 'TYPING', 'SENTENCE')),
    CONSTRAINT ck_session_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'ABANDONED')),
    CONSTRAINT ck_session_counts CHECK (total_questions >= 0 AND correct_answers BETWEEN 0 AND total_questions),
    CONSTRAINT ck_session_dates CHECK (completed_at IS NULL OR completed_at >= started_at)
);
CREATE INDEX idx_study_sessions_mode_started ON study_sessions(training_mode, started_at);

CREATE TABLE study_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    word_id BIGINT,
    sentence_id BIGINT,
    direction VARCHAR(30) NOT NULL,
    user_answer VARCHAR(4000),
    result VARCHAR(30) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_study_attempts_session FOREIGN KEY (session_id) REFERENCES study_sessions(id),
    CONSTRAINT fk_study_attempts_word FOREIGN KEY (word_id) REFERENCES words(id),
    CONSTRAINT fk_study_attempts_sentence FOREIGN KEY (sentence_id) REFERENCES sentences(id),
    CONSTRAINT ck_attempt_target CHECK ((word_id IS NOT NULL AND sentence_id IS NULL) OR (word_id IS NULL AND sentence_id IS NOT NULL)),
    CONSTRAINT ck_attempt_direction CHECK (direction IN ('BG_TO_RU', 'RU_TO_BG')),
    CONSTRAINT ck_attempt_result CHECK (result IN ('CORRECT', 'INCORRECT', 'SKIPPED'))
);
CREATE INDEX idx_study_attempts_session_created ON study_attempts(session_id, created_at);
CREATE INDEX idx_study_attempts_word ON study_attempts(word_id);
CREATE INDEX idx_study_attempts_sentence ON study_attempts(sentence_id);
