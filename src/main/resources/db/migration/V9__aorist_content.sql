CREATE TABLE aorist_datasets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace VARCHAR(100) NOT NULL UNIQUE,
    metadata_json CLOB NOT NULL,
    dataset_revision INTEGER NOT NULL CHECK (dataset_revision > 0),
    file_hash VARCHAR(64),
    version BIGINT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE TABLE aorist_verbs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL REFERENCES aorist_datasets(id),
    external_id VARCHAR(100) NOT NULL,
    lemma VARCHAR(255) NOT NULL,
    russian VARCHAR(1000) NOT NULL,
    aspect VARCHAR(20) NOT NULL CHECK (aspect IN ('imperfective','perfective')),
    tense VARCHAR(20) NOT NULL CHECK (tense = 'aorist'),
    reflexive_particle VARCHAR(2) CHECK (reflexive_particle IN ('се','си')),
    study_group VARCHAR(100) NOT NULL,
    note VARCHAR(4000) NOT NULL,
    source_json CLOB NOT NULL,
    search_text VARCHAR(100000) NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    archived BOOLEAN DEFAULT FALSE NOT NULL,
    version BIGINT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UNIQUE(dataset_id, external_id),
    CHECK (CHAR_LENGTH(TRIM(external_id)) > 0 AND CHAR_LENGTH(TRIM(lemma)) > 0
        AND CHAR_LENGTH(TRIM(russian)) > 0 AND CHAR_LENGTH(TRIM(study_group)) > 0)
);
CREATE INDEX idx_aorist_verbs_filters ON aorist_verbs(dataset_id, archived, study_group, aspect, id);
CREATE TABLE aorist_forms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verb_id BIGINT NOT NULL REFERENCES aorist_verbs(id),
    person VARCHAR(3) NOT NULL CHECK (person IN ('1sg','2sg','3sg','1pl','2pl','3pl')),
    position INTEGER NOT NULL CHECK (position > 0),
    answer_text VARCHAR(255) NOT NULL CHECK (CHAR_LENGTH(TRIM(answer_text)) > 0),
    normalized_key VARCHAR(255) NOT NULL,
    UNIQUE(verb_id, person, position), UNIQUE(verb_id, person, normalized_key)
);
CREATE TABLE aorist_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verb_id BIGINT NOT NULL REFERENCES aorist_verbs(id),
    person VARCHAR(3) NOT NULL CHECK (person IN ('1sg','2sg','3sg','1pl','2pl','3pl')),
    total_attempts INTEGER DEFAULT 0 NOT NULL,
    correct_attempts INTEGER DEFAULT 0 NOT NULL,
    successful_review_count INTEGER DEFAULT 0 NOT NULL,
    consecutive_correct INTEGER DEFAULT 0 NOT NULL,
    last_reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    next_review_at TIMESTAMP(6) WITH TIME ZONE,
    repetition_interval INTEGER DEFAULT 0 NOT NULL,
    UNIQUE(verb_id, person),
    CHECK (total_attempts >= 0 AND correct_attempts BETWEEN 0 AND total_attempts
        AND successful_review_count BETWEEN 0 AND correct_attempts
        AND consecutive_correct BETWEEN 0 AND correct_attempts AND repetition_interval >= 0)
);
CREATE INDEX idx_aorist_progress_due ON aorist_progress(person, next_review_at);
CREATE TABLE aorist_import_receipts (
    request_id UUID PRIMARY KEY,
    import_id UUID NOT NULL UNIQUE,
    dataset_id BIGINT NOT NULL REFERENCES aorist_datasets(id),
    request_hash VARCHAR(64) NOT NULL,
    file_hash VARCHAR(64) NOT NULL,
    metadata_json CLOB NOT NULL,
    summary_json CLOB NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
